CREATE TABLE IF NOT EXISTS content_items(id VARCHAR(80) PRIMARY KEY, payload CLOB NOT NULL);
CREATE TABLE IF NOT EXISTS completions(lesson_id VARCHAR(80) PRIMARY KEY, completed_at VARCHAR(40) NOT NULL);
CREATE TABLE IF NOT EXISTS preferences(id INT PRIMARY KEY, payload CLOB NOT NULL);
CREATE TABLE IF NOT EXISTS reviews(card_id VARCHAR(80) PRIMARY KEY, rating INT NOT NULL, repetitions INT NOT NULL, due_at VARCHAR(40) NOT NULL);
CREATE TABLE IF NOT EXISTS media(id VARCHAR(80) PRIMARY KEY, name VARCHAR(255) NOT NULL, mime VARCHAR(80) NOT NULL, bytes BLOB NOT NULL);
